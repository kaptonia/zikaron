pub fn desk_names() -> Vec<&'static str> {
    let mut out: Vec<&'static str> = Vec::new();
    for (_, name, _) in zikaron_glue::door::DESK {
        if !Reason::ALL.iter().any(|r| r.as_str() == name) && !out.contains(&name) {
            out.push(name);
        }
    }
    out
}

pub fn desk_reason(code: &str) -> Option<(Reason, Option<&'static str>)> {
    let (name, token) = zikaron_glue::door::desk_reason(code)?;
    Some((Reason::ALL.iter().copied().find(|r| r.as_str() == name).unwrap_or(Reason::Desk(name)), token))
}

