#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Rule {
    Retraction,
    Withheld,
    Revocation,
    Annotation,
    WouldBreak,
}

impl Rule {
    pub const ALL: [Rule; 5] = [Rule::Retraction, Rule::Withheld, Rule::Revocation, Rule::Annotation, Rule::WouldBreak];

    pub fn as_str(self) -> &'static str {
        match self {
            Rule::Retraction => "retraction",
            Rule::Withheld => "withheld",
            Rule::Revocation => "revocation",
            Rule::Annotation => "annotation",
            Rule::WouldBreak => "wouldBreak",
        }
    }

    pub fn of_str(s: &str) -> Option<Rule> {
        Rule::ALL.into_iter().find(|r| r.as_str() == s)
    }
}

